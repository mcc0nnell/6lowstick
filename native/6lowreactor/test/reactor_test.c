#include "s6_reactor.h"
#include <assert.h>
#include <stdio.h>
#include <string.h>

static const unsigned char key[32] = {
  6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6,6
};
typedef struct {
    int counter;
    int outcomes[2]; // 0 valid; 1 no receipt; 2 invalid; 3 transport error; 4 lost receipt
    int sends[2];
    int activations;
    char seen_id[33];
} harness_t;
static bool sequence_nonce(void *handle, char out[25]) {
    harness_t *h = handle;
    snprintf(out, 25, "%024x", ++h->counter);
    return true;
}
static bool repeating_nonce(void *handle, char out[25]) {
    (void)handle;
    strcpy(out, "000000000000000000000001");
    return true;
}
static s6_link_result_t transmit(void *handle, const char *route, const char *wire,
                                 const char *id, const char *receiver, const char *nonce,
                                 char response[S6_MAX_WIRE]) {
    harness_t *h = handle;
    int idx = strcmp(route, "thread") == 0 ? 0 : 1;
    h->sends[idx]++;
    assert(s6_verify_alert(key, sizeof(key), wire));
    int mode = h->outcomes[idx];
    if (mode == 3) return S6_LINK_ERROR;
    if (mode == 1) return S6_LINK_RESPONSE;
    if (strcmp(h->seen_id, id) != 0) {
        h->activations++;
        strcpy(h->seen_id, id);
    }
    assert(s6_sign_receipt(key, sizeof(key), id, receiver, nonce, response));
    if (mode == 2) response[strlen(response) - 1] =
        response[strlen(response) - 1] == '0' ? '1' : '0';
    if (mode == 4) response[0] = '\0';
    return S6_LINK_RESPONSE;
}
static s6_report_t run(harness_t *h) {
    s6_report_t report;
    assert(s6_deliver(key, sizeof(key), "drill1", "haptic", true,
                      sequence_nonce, h, transmit, h, &report));
    assert(report.simulation && !report.physical_radio_verified && !report.human_acknowledged);
    return report;
}
int main(void) {
    char wire[S6_MAX_WIRE], receipt[S6_MAX_WIRE];
    assert(s6_sign_alert(key, sizeof(key), "drill1", wire));
    assert(s6_verify_alert(key, sizeof(key), wire));
    // Shared fixed vectors generated by the existing Node.js HMAC implementation.
    assert(strcmp(wire, "EA2|drill1|NOTIFY|37c8580744dd95834fc8941d210c5cee") == 0);
    wire[4] = 'z';
    assert(!s6_verify_alert(key, sizeof(key), wire));
    assert(s6_sign_receipt(key, sizeof(key), "drill1", "haptic",
                           "000000000000000000000001", receipt));
    assert(strcmp(receipt, "R2|drill1|haptic|000000000000000000000001|3dfecf3ac6384e4ab2deeaffa374f1d6") == 0);
    assert(s6_verify_receipt(key, sizeof(key), "drill1", "haptic",
                             "000000000000000000000001", receipt));
    assert(!s6_verify_receipt(key, sizeof(key), "drill1", "other",
                              "000000000000000000000001", receipt));
    assert(!s6_verify_receipt(key, sizeof(key), "drill1", "haptic",
                              "000000000000000000000002", receipt));
    assert(!s6_sign_receipt(key, sizeof(key), "drill1", "haptic", "bad", receipt));
    harness_t healthy = {0};
    s6_report_t a = run(&healthy);
    assert(a.count == 1 && healthy.sends[1] == 0 &&
           strcmp(a.confirmed_route, "thread") == 0);
    harness_t down = {.outcomes = {1,0}};
    s6_report_t b = run(&down);
    assert(b.count == 2 && strcmp(b.confirmed_route, "lora-p2p") == 0 &&
           strcmp(b.attempts[0].outcome, "no_authenticated_receipt") == 0);
    harness_t lost = {.outcomes = {4,0}};
    s6_report_t c = run(&lost);
    assert(c.count == 2 && lost.activations == 1 &&
           strcmp(c.confirmed_route, "lora-p2p") == 0);
    harness_t tampered = {.outcomes = {2,0}};
    s6_report_t d = run(&tampered);
    assert(d.count == 2 && strcmp(d.attempts[0].outcome, "invalid_app_receipt") == 0);
    harness_t both = {.outcomes = {1,1}};
    s6_report_t e = run(&both);
    assert(e.count == 2 && !e.confirmed_route && strcmp(e.status, "unconfirmed") == 0);
    harness_t error = {.outcomes = {3,0}};
    s6_report_t f = run(&error);
    assert(strcmp(f.attempts[0].outcome, "transport_error") == 0);
    harness_t invalid = {.outcomes = {1,0}};
    s6_report_t reject;
    assert(!s6_deliver(key, sizeof(key), "drill1", "haptic", false,
                       sequence_nonce, &invalid, transmit, &invalid, &reject));
    assert(invalid.sends[0] == 0 && invalid.sends[1] == 0);
    assert(!s6_deliver(key, sizeof(key), "x|invalid", "haptic", true,
                       sequence_nonce, &invalid, transmit, &invalid, &reject));
    assert(invalid.sends[0] == 0 && invalid.sends[1] == 0);
    assert(!s6_deliver(key, sizeof(key), "drill1", "haptic", true,
                       repeating_nonce, NULL, transmit, &invalid, &reject));
    assert(invalid.sends[0] == 1 && invalid.sends[1] == 0);
    puts("6lowReactor native simulation contract: PASS");
    return 0;
}
