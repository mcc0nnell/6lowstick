// Separate synthetic output witness for 6lowFlare application admissions.
// Never drives a light/motor, never samples an independent physical sensor.
const NONCE = /^[0-9a-f]{24}$/;
const MODES = ['light', 'haptic', 'text'];
const time = n => Number.isSafeInteger(n) && n >= 0;

// Distinct calls record model request vs fixture observation; neither can
// be promoted into a claim of measured physical activation or human detection.
export function createFlareOutputRecorder({modalities = ['light', 'haptic']} = {}) {
  if (!Array.isArray(modalities) || !modalities.length || modalities.length > 3 ||
      new Set(modalities).size !== modalities.length ||
      modalities.some(m => !MODES.includes(m)))
    throw new TypeError('invalid output recorder modalities');
  const records = new Map();
  return {
    // Called only after a validated process-local 6lowFlare receive.
    request(applicationAdmission, {at} = {}) {
      if (!applicationAdmission || applicationAdmission.applicationReceived !== true ||
          !NONCE.test(applicationAdmission.nonce) || !time(at) ||
          !Array.isArray(applicationAdmission.requestedModalities) ||
          applicationAdmission.requestedModalities.some(m => !MODES.includes(m)) ||
          records.size >= 128 || records.has(applicationAdmission.nonce))
        return false;
      const requested = applicationAdmission.requestedModalities.filter(m => modalities.includes(m));
      if (!requested.length) return false;
      records.set(applicationAdmission.nonce, {nonce: applicationAdmission.nonce,
        requestedAt: at, requested, fixtureObserved: new Map()});
      return true;
    },
    // Strictly a separate **scripted fixture**, not actual photometry or
    // accelerometry. No implicit evidence is generated by request().
    observeFixture({nonce, modality, at, fixture = 'software-fixture'} = {}) {
      const record = records.get(nonce);
      if (!record || !record.requested.includes(modality) || !time(at) ||
          at < record.requestedAt || fixture !== 'software-fixture' ||
          record.fixtureObserved.has(modality)) return false;
      record.fixtureObserved.set(modality, at);
      return true;
    },
    evidence() {
      return [...records.values()].map(rec => Object.freeze({
        nonce: rec.nonce,
        simulated: true,
        requestedAt: rec.requestedAt,
        requestedModalities: [...rec.requested],
        fixtureObservedModalities: [...rec.fixtureObserved.keys()],
        absentFixtureObservations: rec.requested.filter(m => !rec.fixtureObserved.has(m)),
        physicalOutput: 'unknown',
        humanDetected: 'unknown',
        humanUnderstood: 'unknown'
      }));
    },
    reset() { records.clear(); }
  };
}
